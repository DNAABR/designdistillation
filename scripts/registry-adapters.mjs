import fs from "node:fs";
import path from "node:path";

export function buildRegistryArtifacts({ root = process.cwd() } = {}) {
  const manifest = readJson(path.join(root, "registry", "manifest.json"));
  return {
    "design-tokens.css": generateCssVariables({ root }),
    "tailwind-theme.css": generateTailwindTheme({ root, manifest }),
    "components.css": fs.readFileSync(path.join(root, "registry", "source", "css", "components.css"), "utf8")
  };
}

export function generateCssVariables({ root = process.cwd() } = {}) {
  const manifest = readJson(path.join(root, "tokens", "manifest.json"));
  const baseTree = loadBaseTokenTree({ root, manifest });
  const lightTree = deepMerge(baseTree, readJson(path.join(root, "tokens", manifest.themes.light)));
  const lightIndex = buildTokenIndex(lightTree);
  const lines = [
    "/* Generated by Design Distillation v0.6. Do not edit by hand. */",
    ":root, [data-dd-theme=\"light\"] {",
    "  color-scheme: light;",
    ...renderDeclarations(lightIndex, () => true),
    "}",
    ""
  ];

  for (const theme of ["dark", "high-contrast"]) {
    const themedTree = deepMerge(baseTree, readJson(path.join(root, "tokens", manifest.themes[theme])));
    const themedIndex = buildTokenIndex(themedTree);
    lines.push("[data-dd-theme=\"" + theme + "\"] {");
    lines.push("  color-scheme: " + (theme === "dark" ? "dark" : "light") + ";");
    lines.push(...renderDeclarations(themedIndex, (tokenPath) => tokenPath.startsWith("semantic.color.")));
    lines.push("}", "");
  }

  return lines.join("\n");
}

export function generateTailwindTheme({ root = process.cwd(), manifest } = {}) {
  const registryManifest = manifest ?? readJson(path.join(root, "registry", "manifest.json"));
  const tokenMap = registryManifest.adapters?.["tailwind-v4"]?.token_map ?? {};
  const lines = [
    "/* Generated Design Distillation aliases for Tailwind CSS v4. */",
    "/* Import design-tokens.css before this file. */",
    "@theme inline {"
  ];

  for (const [tailwindName, tokenPath] of Object.entries(tokenMap).sort(([a], [b]) => a.localeCompare(b))) {
    lines.push("  --" + tailwindName + ": var(" + cssVariableName(tokenPath) + ");");
  }
  lines.push("}", "");
  return lines.join("\n");
}

export function installRegistryEntries({
  root = process.cwd(),
  outDir,
  adapter = "css",
  ids = []
}) {
  if (!outDir) throw new Error("Registry install requires an output directory.");
  const manifest = readJson(path.join(root, "registry", "manifest.json"));
  if (!manifest.adapters?.[adapter]) throw new Error('Unknown registry adapter "' + adapter + '".');

  const entries = manifest.entries.map((file) => readJson(path.join(root, file)));
  const byId = new Map(entries.map((entry) => [entry.id, entry]));
  const selectedIds = ids.length ? ids : entries.map((entry) => entry.id);
  const selected = selectedIds.map((id) => {
    const entry = byId.get(id);
    if (!entry) throw new Error('Unknown registry entry "' + id + '".');
    return entry;
  });

  const artifacts = buildRegistryArtifacts({ root });
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "design-tokens.css"), artifacts["design-tokens.css"]);
  fs.writeFileSync(path.join(outDir, "components.css"), artifacts["components.css"]);

  if (adapter === "tailwind-v4") {
    fs.writeFileSync(path.join(outDir, "tailwind-theme.css"), artifacts["tailwind-theme.css"]);
  }

  const written = ["design-tokens.css", "components.css"];
  if (adapter === "tailwind-v4") written.push("tailwind-theme.css");

  if (adapter === "react") {
    const componentsDir = path.join(outDir, "components");
    fs.mkdirSync(componentsDir, { recursive: true });
    const exportLines = [];

    for (const entry of selected) {
      const source = entry.implementation.adapters.react.source;
      const basename = path.basename(source);
      fs.copyFileSync(path.join(root, source), path.join(componentsDir, basename));
      written.push(path.join("components", basename).replaceAll("\\", "/"));
      exportLines.push('export * from "./' + basename.replace(/\.tsx$/, "") + '";');
    }

    fs.writeFileSync(path.join(componentsDir, "index.ts"), exportLines.join("\n") + "\n");
    written.push("components/index.ts");
  }

  const selection = {
    version: manifest.version,
    adapter,
    entries: selected.map((entry) => entry.id),
    license_note: manifest.install.license_note
  };
  fs.writeFileSync(path.join(outDir, "registry-selection.json"), JSON.stringify(selection, null, 2) + "\n");
  written.push("registry-selection.json");

  return { entries: selected, written, licenseNote: manifest.install.license_note };
}

export function listRegistryEntries({ root = process.cwd() } = {}) {
  const manifest = readJson(path.join(root, "registry", "manifest.json"));
  return manifest.entries.map((file) => readJson(path.join(root, file)));
}

export function resolveTokenValue({ root = process.cwd(), theme = "light", tokenPath }) {
  const manifest = readJson(path.join(root, "tokens", "manifest.json"));
  if (!manifest.themes[theme]) throw new Error('Unknown theme "' + theme + '".');
  const tree = deepMerge(
    loadBaseTokenTree({ root, manifest }),
    readJson(path.join(root, "tokens", manifest.themes[theme]))
  );
  const index = buildTokenIndex(tree);
  return resolveRecord(index, tokenPath).value;
}

function loadBaseTokenTree({ root, manifest }) {
  let tree = {};
  for (const source of manifest.sources) {
    tree = deepMerge(tree, readJson(path.join(root, "tokens", source)));
  }
  return tree;
}

function buildTokenIndex(tree) {
  const index = new Map();
  collectTokenLeaves(tree, [], undefined, index);
  return index;
}

function collectTokenLeaves(node, segments, inheritedType, index) {
  if (!node || typeof node !== "object" || Array.isArray(node)) return;
  const type = node.$type ?? inheritedType;
  if (Object.prototype.hasOwnProperty.call(node, "$value")) {
    index.set(segments.join("."), { value: node.$value, type });
  }
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    collectTokenLeaves(value, [...segments, key], type, index);
  }
}

function resolveRecord(index, tokenPath, stack = []) {
  const record = index.get(tokenPath);
  if (!record) throw new Error('Unknown token "' + tokenPath + '".');
  if (stack.includes(tokenPath)) throw new Error("Circular token alias: " + [...stack, tokenPath].join(" -> "));

  const directAlias = typeof record.value === "string" && /^\{[^}]+\}$/.test(record.value)
    ? record.value.slice(1, -1)
    : null;
  if (directAlias) {
    const target = resolveRecord(index, directAlias, [...stack, tokenPath]);
    return { value: target.value, type: record.type ?? target.type };
  }

  return {
    value: resolveNestedValue(index, record.value, [...stack, tokenPath]),
    type: record.type
  };
}

function resolveNestedValue(index, value, stack) {
  if (typeof value === "string" && /^\{[^}]+\}$/.test(value)) {
    return resolveRecord(index, value.slice(1, -1), stack).value;
  }
  if (Array.isArray(value)) return value.map((item) => resolveNestedValue(index, item, stack));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, resolveNestedValue(index, item, stack)])
    );
  }
  return value;
}

function renderDeclarations(index, predicate) {
  const lines = [];
  for (const tokenPath of [...index.keys()].filter(predicate).sort()) {
    const resolved = resolveRecord(index, tokenPath);
    for (const [name, value] of expandCssValues(tokenPath, resolved.value, resolved.type)) {
      lines.push("  " + name + ": " + value + ";");
    }
  }
  return lines;
}

function expandCssValues(tokenPath, value, type) {
  const name = cssVariableName(tokenPath);

  if (type === "typography" && value && !Array.isArray(value)) {
    return [
      [name, formatTypography(value)],
      [name + "-font-family", formatCssValue(value.fontFamily, "fontFamily")],
      [name + "-font-size", formatCssValue(value.fontSize)],
      [name + "-font-weight", String(value.fontWeight)],
      [name + "-letter-spacing", formatCssValue(value.letterSpacing)],
      [name + "-line-height", String(value.lineHeight)]
    ];
  }

  if (type === "transition" && value && !Array.isArray(value)) {
    return [
      [name, formatTransition(value)],
      [name + "-duration", formatCssValue(value.duration)],
      [name + "-delay", formatCssValue(value.delay)],
      [name + "-timing-function", formatCssValue(value.timingFunction, "cubicBezier")]
    ];
  }

  return [[name, formatCssValue(value, type)]];
}

function formatCssValue(value, type) {
  if (typeof value === "string" || typeof value === "number") return String(value);
  if (Array.isArray(value)) {
    if (type === "fontFamily" || value.every((item) => typeof item === "string")) {
      return value.map(formatFontFamily).join(", ");
    }
    if (type === "cubicBezier" || (value.length === 4 && value.every((item) => typeof item === "number"))) {
      return "cubic-bezier(" + value.join(", ") + ")";
    }
    if (type === "shadow") return value.map(formatShadow).join(", ");
    throw new Error("Unsupported array token value for CSS output.");
  }
  if (!value || typeof value !== "object") throw new Error("Unsupported token value for CSS output.");

  if ("value" in value && "unit" in value) return String(value.value) + value.unit;
  if (value.colorSpace && value.hex) return formatColor(value);
  if (type === "shadow" || ("color" in value && "blur" in value)) return formatShadow(value);
  if ("fontFamily" in value && "fontSize" in value) return formatTypography(value);
  if ("duration" in value && "timingFunction" in value) return formatTransition(value);

  throw new Error("Unsupported composite token value for CSS output.");
}

function formatColor(color) {
  const alpha = typeof color.alpha === "number" ? color.alpha : 1;
  if (alpha >= 1) return color.hex;
  const hex = color.hex.replace("#", "");
  const normalized = hex.length === 3 ? hex.split("").map((char) => char + char).join("") : hex.slice(0, 6);
  const red = parseInt(normalized.slice(0, 2), 16);
  const green = parseInt(normalized.slice(2, 4), 16);
  const blue = parseInt(normalized.slice(4, 6), 16);
  return "rgb(" + red + " " + green + " " + blue + " / " + alpha + ")";
}

function formatShadow(shadow) {
  return [
    formatCssValue(shadow.offsetX),
    formatCssValue(shadow.offsetY),
    formatCssValue(shadow.blur),
    formatCssValue(shadow.spread),
    formatCssValue(shadow.color, "color")
  ].join(" ");
}

function formatTypography(value) {
  return [
    String(value.fontWeight),
    formatCssValue(value.fontSize) + "/" + String(value.lineHeight),
    formatCssValue(value.fontFamily, "fontFamily")
  ].join(" ");
}

function formatTransition(value) {
  return [
    formatCssValue(value.duration),
    formatCssValue(value.timingFunction, "cubicBezier"),
    formatCssValue(value.delay)
  ].join(" ");
}

function formatFontFamily(value) {
  const text = String(value);
  return /\s/.test(text) ? '"' + text.replaceAll('"', '\\"') + '"' : text;
}

function cssVariableName(tokenPath) {
  return "--dd-" + tokenPath.replaceAll(".", "-").replace(/[^a-zA-Z0-9_-]/g, "-");
}

function deepMerge(left, right) {
  if (!left || typeof left !== "object" || Array.isArray(left)) return clone(right);
  if (!right || typeof right !== "object" || Array.isArray(right)) return clone(right);
  const result = clone(left);
  for (const [key, value] of Object.entries(right)) {
    result[key] = key in result ? deepMerge(result[key], value) : clone(value);
  }
  return result;
}

function clone(value) {
  if (value === undefined) return undefined;
  return JSON.parse(JSON.stringify(value));
}

function readJson(file) {
  const content = fs.readFileSync(file, "utf8");
  return JSON.parse(content.charCodeAt(0) === 0xFEFF ? content.slice(1) : content);
}
